    def _refresh_ports(self):
        ports = [p.device for p in serial.tools.list_ports.comports()]
        self.port_combo["values"] = ports
        if ports:
            self.port_combo.current(0)

    def toggle_connection(self):
        if self.reader_thread and self.reader_thread.is_alive():
            self._disconnect()
        else:
            self._connect()

    def _connect(self):
        port = self.port_combo.get()
        if not port:
            self.status_label.config(text="● No port selected.", fg="#e74c3c")
            return

        self.stop_event.clear()
        self.reader_thread = SerialReaderThread(
            port, self.data_queue, self.stop_event)
        self.reader_thread.start()

        self.connect_btn.config(text="Disconnect")
        self.status_label.config(
            text=f"● Connecting to {port}...", fg="#f39c12")

    def _disconnect(self):
        if self.recording:
            self._stop_recording(auto=True)
        self.stop_event.set()
        if self.reader_thread:
            self.reader_thread.join(timeout=2)
        self.connect_btn.config(text="Connect")
        self.status_label.config(text="● Disconnected", fg="#e74c3c")

   
    def toggle_recording(self):
        if self.recording:
            self._stop_recording(auto=False)
            return

        if not (self.reader_thread and self.reader_thread.is_alive()):
            messagebox.showwarning(
                "Warning", "Please connect the device before starting the recording.")
            return

        dialog = PatientInfoDialog(self.root)
        if not dialog.result:
            return

        self.patient_info = dialog.result
        self.record_ecg = []
        self.record_bpm = []
        self.record_start_time = time.time()
        self.recording = True
        self.record_btn.config(text="⏹ Stop & Save")

    def _stop_recording(self, auto):
        self.recording = False
        self.record_btn.config(text="🔴 Record ECG (max 4 min)")

        ecg_data = list(self.record_ecg)
        bpm_data = list(self.record_bpm)
        patient_info = dict(self.patient_info) if self.patient_info else {
            "name": "Unknown", "age": "-", "mobile": ""}

        if len(ecg_data) < 10:
            self.record_status_var.set("")
            if not auto:
                messagebox.showwarning(
                    "Warning", "Not enough ECG data recorded, could not generate PDF.")
            return

        self.record_status_var.set("Creating PDF..... ")
        threading.Thread(target=self._generate_and_send,
                         args=(ecg_data, bpm_data, patient_info), daemon=True).start()

    def _generate_and_send(self, ecg_data, bpm_data, patient_info):
        try:
            pdf_path = generate_ecg_pdf_report(ecg_data, bpm_data, patient_info)
            self.root.after(0, lambda: self._on_pdf_done(pdf_path, None))

            mobile = patient_info.get("mobile", "").strip()
            if mobile:
                self.root.after(0, lambda: self.record_status_var.set("Sending via WhatsApp..."))
                send_thread = threading.Thread(target=self._send_whatsapp_worker,
                                               args=(mobile, pdf_path), daemon=True)
                send_thread.start()
        except Exception as e:
            self.root.after(0, lambda: self._on_pdf_done(None, e))

    def _send_whatsapp_worker(self, mobile, pdf_path):
        try:
            success = send_whatsapp_pdf(mobile, pdf_path)
            if success:
                self.root.after(0, lambda: self.record_status_var.set("WhatsApp sent ✓"))
            else:
                self.root.after(0, lambda: self.record_status_var.set("WhatsApp send failed"))
        except Exception as e:
            error_msg = f"WhatsApp send error: {e}"
            self.root.after(0, lambda: messagebox.showerror("WhatsApp Error", error_msg))
            self.root.after(0, lambda: self.record_status_var.set("WhatsApp send failed"))

    def _on_pdf_done(self, path, error):
        self.record_status_var.set("")
        if error:
            messagebox.showerror("ERROR", f"Error in generating PDF:\n{error}")
        else:
            messagebox.showinfo(
                "Save complete", f"ECG report has been saved:\n{path}")

    
    def poll_queue(self):
        got_data = False
        try:
            while True:
                item = self.data_queue.get_nowait()
                if item[0] == "ERROR":
                    self.status_label.config(text=f"● {item[1]}", fg="#e74c3c")
                    self.connect_btn.config(text="Connect")
                    if self.recording:
                        self._stop_recording(auto=True)
                elif item[0] == "DATA":
                    _, ecg_val, bpm_val = item
                    self.ecg_buffer.append(ecg_val)
                    if bpm_val > 0:
                        self.last_bpm = bpm_val

                    if ecg_val == 0 and bpm_val == 0:
                        self.zero_streak += 1
                    else:
                        self.zero_streak = 0

                    if self.recording:
                        self.record_ecg.append(ecg_val)
                        if bpm_val > 0:
                            self.record_bpm.append(bpm_val)

                    got_data = True
        except queue.Empty:
            pass

        if got_data:
            self.status_label.config(text="● Connected", fg=COLOR_ACCENT)
            self.line.set_ydata(list(self.ecg_buffer))
            self.canvas.draw_idle()

            self.bpm_var.set(
                f"{self.last_bpm} BPM" if self.last_bpm else "-- BPM")
            if self.last_bpm:
                if 60 <= self.last_bpm <= 100:
                    self.bpm_label.config(fg=COLOR_ACCENT)
                else:
                    self.bpm_label.config(fg="#e67e22")

            if self.zero_streak > 15:
                self.warn_var.set("⚠ Leads Off Detected — CHECK ELECTRODE")
            else:
                self.warn_var.set("")

        # recording timer
        if self.recording and self.record_start_time is not None:
            elapsed = time.time() - self.record_start_time
            mm, ss = divmod(int(elapsed), 60)
            self.record_status_var.set(
                f"Recording.... {mm:02d}:{ss:02d} / 04:00")
            if elapsed >= RECORD_LIMIT_SECONDS:
                self._stop_recording(auto=True)

        self.root.after(POLL_MS, self.poll_queue)

    def on_close(self):
        self.stop_event.set()
        if self.reader_thread:
            self.reader_thread.join(timeout=2)
        self.root.destroy()


