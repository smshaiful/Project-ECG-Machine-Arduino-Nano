class SerialReaderThread(threading.Thread):
    def __init__(self, port, data_queue, stop_event):
        super().__init__(daemon=True)
        self.port = port
        self.data_queue = data_queue
        self.stop_event = stop_event
        self.ser = None

    def run(self):
        try:
            self.ser = serial.Serial(self.port, BAUD_RATE, timeout=1)
            time.sleep(2)
            self.ser.reset_input_buffer()
        except serial.SerialException as e:
            self.data_queue.put(("ERROR", f"UNABLE TO OPEN PORT: {e}"))
            return

        while not self.stop_event.is_set():
            try:
                raw = self.ser.readline()
                if not raw:
                    continue
                line = raw.decode("utf-8", errors="ignore").strip()

                if not line.startswith("ECG:") or ",BPM:" not in line:
                    continue 

                ecg_part, bpm_part = line.split(",BPM:")
                ecg_val = int(ecg_part.replace("ECG:", "").strip())
                bpm_val = int(bpm_part.strip())
                self.data_queue.put(("DATA", ecg_val, bpm_val))

            except (ValueError, UnicodeDecodeError):
                continue
            except serial.SerialException as e:
                self.data_queue.put(("ERROR", f"Connection dropped: {e}"))
                break

        if self.ser and self.ser.is_open:
            self.ser.close()




def _style_ecg_strip(ax):
    ax.set_facecolor("#fff0f0")
    ax.set_ylim(0, 1023)
    ax.xaxis.set_minor_locator(MultipleLocator(0.2))
    ax.xaxis.set_major_locator(MultipleLocator(1.0))
    ax.yaxis.set_minor_locator(MultipleLocator(51.15))
    ax.yaxis.set_major_locator(MultipleLocator(204.6))
    ax.grid(which="minor", color="#ffc4c4", linewidth=0.3)
    ax.grid(which="major", color="#ff8080", linewidth=0.6)
    ax.set_yticklabels([])
    for spine in ax.spines.values():
        spine.set_color("#e08080")
        spine.set_linewidth(0.6)


def generate_ecg_pdf_report(ecg_data, bpm_data, patient_info):
    os.makedirs(REPORTS_DIR, exist_ok=True)

    now = datetime.now()
    duration_sec = len(ecg_data) * SAMPLE_INTERVAL_MS / 1000
    dur_mm, dur_ss = divmod(int(duration_sec), 60)
    duration_str = f"{dur_mm:02d} min {dur_ss:02d} sec"

    if bpm_data:
        avg_bpm = round(sum(bpm_data) / len(bpm_data))
        min_bpm = min(bpm_data)
        max_bpm = max(bpm_data)
    else:
        avg_bpm = min_bpm = max_bpm = "N/A"

    safe_name = "".join(
        c for c in patient_info.get("name", "Unknown") if c.isalnum() or c in (" ", "_")
    ).strip().replace(" ", "_") or "Unknown"
    filename = f"ECG_Report_{safe_name}_{now.strftime('%Y%m%d_%H%M%S')}.pdf"
    filepath = os.path.join(REPORTS_DIR, filename)

    samples_per_strip = int(STRIP_SECONDS * 1000 / SAMPLE_INTERVAL_MS)
    total_strips = max(1, math.ceil(len(ecg_data) / samples_per_strip))

    with PdfPages(filepath) as pdf:
        strip_idx = 0
        page_num = 1

        while strip_idx < total_strips:
            fig = Figure(figsize=(8.27, 11.69))
            FigureCanvasAgg(fig)

            if page_num == 1:
                fig.text(0.5, 0.965, "ECG REPORT", fontsize=20, weight="bold",
                         ha="center", color="#2c3e50")
                fig.text(0.5, 0.940, "ROBOFUSION 1.0 — Real-Time ECG Monitoring System",
                         fontsize=10, ha="center", color="#7f8c8d")
                fig.text(0.5, 0.922, "Generated by Clever Sapiens (JSTU)",
                         fontsize=8, ha="center", style="italic", color="#95a5a6")
                fig.add_artist(Line2D([0.07, 0.93], [0.905, 0.905],
                                      transform=fig.transFigure, color="#bdc3c7", linewidth=1))

                info_y = 0.875
                gap = 0.024
                left_x, right_x = 0.09, 0.53
                rows = [
                    (f"Patient Name : {patient_info.get('name', '-')}",
                     f"Age : {patient_info.get('age', '-')}"),
                    (f"Date : {now.strftime('%d-%m-%Y')}",
                     f"Time : {now.strftime('%I:%M %p')}"),
                    (f"Duration : {duration_str}", f"Avg BPM : {avg_bpm}"),
                    (f"Min BPM : {min_bpm}", f"Max BPM : {max_bpm}"),
                ]
                for i, (left, right) in enumerate(rows):
                    fig.text(left_x, info_y - i * gap, left,
                             fontsize=10, color="#2c3e50")
                    fig.text(right_x, info_y - i * gap, right,
                             fontsize=10, color="#2c3e50")

                divider_y = info_y - 4 * gap - 0.01
                fig.add_artist(Line2D([0.07, 0.93], [divider_y, divider_y],
                                      transform=fig.transFigure, color="#bdc3c7", linewidth=1))

                top_offset = divider_y - 0.02
                n_strips = min(STRIPS_FIRST_PAGE, total_strips - strip_idx)
            else:
                top_offset = 0.95
                n_strips = min(STRIPS_OTHER_PAGE, total_strips - strip_idx)

            bottom_margin = 0.06
            strip_h = (top_offset - bottom_margin) / max(n_strips, 1)

            for i in range(n_strips):
                s_idx = strip_idx + i
                start = s_idx * samples_per_strip
                end = start + samples_per_strip
                segment = ecg_data[start:end]
                if not segment:
                    continue

                y1 = top_offset - i * strip_h
                y0 = y1 - strip_h + 0.012
                ax = fig.add_axes((0.09, y0, 0.85, strip_h - 0.018))
                _style_ecg_strip(ax)

                t = [j * SAMPLE_INTERVAL_MS /
                     1000 for j in range(len(segment))]
                ax.plot(t, segment, color="#c0392b", linewidth=0.8)
                ax.set_xlim(0, STRIP_SECONDS)
                ax.tick_params(labelsize=6, colors="#7f8c8d")
                ax.text(0.005, 0.86, f"{s_idx * STRIP_SECONDS}s\u2013{(s_idx + 1) * STRIP_SECONDS}s",
                        transform=ax.transAxes, fontsize=6, color="#7f8c8d")
                if i == n_strips - 1:
                    ax.set_xlabel("Time (seconds)",
                                  fontsize=7, color="#7f8c8d")

            fig.text(0.5, 0.02, f"Page {page_num}   \u2022   ROBOFUSION 1.0   \u2022   Clever Sapiens (JSTU)",
                     ha="center", fontsize=7, color="#95a5a6")

            pdf.savefig(fig)
            strip_idx += n_strips
            page_num += 1

    return filepath





def send_whatsapp_pdf(phone_number, pdf_path):

    """

    Copies the PDF file to the Windows clipboard via PowerShell,

    opens WhatsApp Web, and simulates Ctrl+V and Enter to send.

    """

    try:

        

        abs_path = os.path.abspath(pdf_path)

        ps_command = f"Set-Clipboard -Path '{abs_path}'"

        subprocess.run(["powershell", "-command", ps_command], check=True)



        # 2. Open default browser to WhatsApp Web chat for this number

        url = f"https://web.whatsapp.com/send?phone={phone_number}"

        webbrowser.open(url)



     

        time.sleep(20)



        pyautogui.hotkey('ctrl', 'v')

       

        

        time.sleep(3)



        

        pyautogui.press('enter')

       


        time.sleep(5)

       


        pyautogui.hotkey('ctrl', 'w')



        return True



    except Exception as e:

        print(f"Error in sending via clipboard: {e}")

        return False 






